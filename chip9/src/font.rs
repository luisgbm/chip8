const FIRST_GLYPH: u8 = b' ';
const BLANK: [u8; GLYPH_HEIGHT] = [0; GLYPH_HEIGHT];

/// The bitmap for `character`, or a blank for anything the font does not cover.
#[must_use]
pub fn glyph(character: char) -> &'static [u8; GLYPH_HEIGHT] {
    let upper = character.to_ascii_uppercase();

    if !upper.is_ascii() {
        return &BLANK;
    }

    match (upper as u8).checked_sub(FIRST_GLYPH) {
        Some(index) => GLYPHS.get(index as usize).unwrap_or(&BLANK),
        None => &BLANK,
    }
}

/// The width in pixels of `text` rendered at `scale`, without the trailing gap.
#[must_use]
pub fn text_width(text: &str, scale: usize) -> usize {
    match text.chars().count() {
        0 => 0,
        count => (count * ADVANCE - 1) * scale,
    }
}
