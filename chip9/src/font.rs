//! A 5x7 bitmap font for the interface.
//!
//! The machine itself only ships sprites for the thirty six digits of base
//! thirty six (see [`crate::cpu::FONT`]), which is not enough to draw a menu,
//! so the front end carries its own ASCII font. Each glyph is seven rows of
//! five pixels, stored in the five low bits of a byte, leftmost pixel in bit 4.

/// Width of a glyph, in pixels.
pub const GLYPH_WIDTH: usize = 5;

/// Height of a glyph, in pixels.
pub const GLYPH_HEIGHT: usize = 7;

/// Horizontal distance between the left edges of two glyphs, in pixels.
pub const ADVANCE: usize = GLYPH_WIDTH + 1;

